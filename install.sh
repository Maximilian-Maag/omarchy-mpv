#!/bin/bash
# omarchy-mpv install script. Run once after cloning, or re-run to update.
#
#   ./install.sh                     install / update everything
#   ./install.sh --uninstall         remove what this script installed, and only that
#   OMARCHY_MPV_BIN=~/.local/bin ./install.sh   where the CLI is symlinked
set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Optional config override, passed through to every CLI invocation. The shell
# tests use it to prove a custom config/mpv.json is honoured; a normal user runs
# the installer bare and the plugin's own config/mpv.json is used.
CLI_ARGS=()
if [[ -n "${OMARCHY_MPV_CONFIG:-}" ]]; then
  CLI_ARGS=(--config "$OMARCHY_MPV_CONFIG")
fi

BIN_SRC="$PLUGIN_DIR/bin/omarchy-mpv"
# Where the CLI is symlinked. Defaults to /usr/local/bin (the Omarchy convention);
# the override lets a user install into their own bin directory, and lets the
# tests exercise the symlink install/uninstall without root.
BIN_DIR="${OMARCHY_MPV_BIN:-/usr/local/bin}"
BIN_DEST="$BIN_DIR/omarchy-mpv"

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}"
HYPR_DIR="$CONFIG_DIR/hypr"
HYPR_MAIN="$HYPR_DIR/hyprland.lua"
FRAGMENT="$HYPR_DIR/mpv-bindings.lua"
REQUIRE_LINE='require("hypr.mpv-bindings")'
MARKER='-- omarchy-mpv keybindings'
HOOK_DEST="$CONFIG_DIR/omarchy/hooks/theme-set.d/mpv-theme-set"
MPV_DIR="$CONFIG_DIR/mpv"
MPV_CONF="$MPV_DIR/mpv.conf"
# The first line of the fragment the CLI generates; the uninstall uses it to
# decide that a file at THEME_CONF is ours (and not something the user wrote).
THEME_MARKER='# Generated by omarchy-mpv from the applied Omarchy theme.'

# Both mpv.conf paths come from the CLI (config/mpv.json's theme_conf_path /
# socket_path), so a custom path is honoured rather than silently ignored. Read
# once here so both the install and the uninstall work from the same values.
PATHS="$("$BIN_SRC" "${CLI_ARGS[@]}" paths 2>/dev/null || true)"
THEME_CONF="$(printf '%s\n' "$PATHS" | sed -n 's/^theme_conf=//p')"
SOCKET_PATH="$(printf '%s\n' "$PATHS" | sed -n 's/^socket=//p')"
if [[ -z "$THEME_CONF" || -z "$SOCKET_PATH" ]]; then
  echo "  WARNING: could not read paths from the CLI — using the built-in defaults."
  THEME_CONF="$MPV_DIR/omarchy-theme.conf"
  SOCKET_PATH="${XDG_RUNTIME_DIR:-/tmp}/omarchy-mpv.sock"
fi
THEME_LINE="include=$THEME_CONF"
SOCKET_LINE="input-ipc-server=$SOCKET_PATH"

say() { echo "  $1"; }
warn() { echo "WARNING: $1" >&2; }

link_cli() {
  chmod +x "$BIN_SRC"
  mkdir -p "$(dirname "$BIN_DEST")" 2>/dev/null || true
  if [[ -L "$BIN_DEST" ]] && [[ "$(readlink -f "$BIN_DEST")" == "$(readlink -f "$BIN_SRC")" ]]; then
    say "omarchy-mpv already on PATH."
  elif (( EUID == 0 )) || [[ -w "$(dirname "$BIN_DEST")" ]]; then
    ln -sf "$BIN_SRC" "$BIN_DEST" && say "Installed $BIN_DEST."
  elif command -v sudo >/dev/null 2>&1; then
    sudo ln -sf "$BIN_SRC" "$BIN_DEST" && say "Installed $BIN_DEST."
  else
    warn "no sudo — add $BIN_SRC to PATH manually."
  fi
}

unlink_ours() {  # unlink_ours <path> <source it must point at>
  local dest="$1" source="$2"
  if [[ -L "$dest" ]] && [[ "$(readlink -f "$dest")" == "$(readlink -f "$source")" ]]; then
    if (( EUID == 0 )) || [[ -w "$(dirname "$dest")" ]]; then
      rm -f "$dest"
    elif command -v sudo >/dev/null 2>&1; then
      sudo rm -f "$dest"
    else
      warn "could not remove $dest — no permission and no sudo."
      return 0
    fi
    say "removed $dest"
  elif [[ -e "$dest" ]]; then
    warn "$dest is not a link into this checkout — left alone."
  fi
}

remove_mpv_conf_lines() {
  [[ -f "$MPV_CONF" ]] || return 0
  local out=() line
  mapfile -t lines < "$MPV_CONF"
  for line in "${lines[@]}"; do
    if [[ $line == "$THEME_LINE" || $line == "$SOCKET_LINE" ]]; then
      # The line went in as a block — a blank line, a `# omarchy-mpv …` marker,
      # then the line — so the marker and its blank line come back out with it.
      # Leaving them behind would stack another marker at every install cycle.
      if (( ${#out[@]} )) && [[ ${out[-1]} == '# omarchy-mpv theme' || ${out[-1]} == '# omarchy-mpv IPC socket' ]]; then
        unset 'out[-1]'
        if (( ${#out[@]} )) && [[ -z ${out[-1]} ]]; then
          unset 'out[-1]'
        fi
      fi
      continue
    fi
    if [[ $line == '# omarchy-mpv integration' ]]; then
      # The header the installer writes when it creates the file itself.
      continue
    fi
    if [[ $line == '# omarchy-mpv: superseded '* ]]; then
      # A pre-existing input-ipc-server= the installer commented out so the
      # plugin's socket wins: restore the user's own line verbatim.
      out+=("${line#'# omarchy-mpv: superseded '}")
      continue
    fi
    out+=("$line")
  done
  kept="$(mktemp)"
  for line in ${out[@]+"${out[@]}"}; do
    printf '%s\n' "$line"
  done > "$kept"
  if [[ ! -s "$kept" ]]; then
    # The installer created the file when the user had none; put that back.
    rm -f "$kept" "$MPV_CONF"
    say "removed $MPV_CONF"
  else
    mv "$kept" "$MPV_CONF"
    say "took the omarchy-mpv lines back out of $MPV_CONF"
  fi
}

remove_require_block() {
  [[ -f "$HYPR_MAIN" ]] || return 0
  grep -qF "$REQUIRE_LINE" "$HYPR_MAIN" || return 0
  # Rebuilt line by line (never `sed -i`): the require line came in as a block —
  # a blank line, the `-- omarchy-mpv keybindings` marker, then the line — so the
  # whole block goes back out, leaving no marker to stack up next time.
  local out=() line
  mapfile -t lines < "$HYPR_MAIN"
  for line in "${lines[@]}"; do
    if [[ $line == "$REQUIRE_LINE" ]]; then
      if (( ${#out[@]} )) && [[ ${out[-1]} == "$MARKER" ]]; then
        unset 'out[-1]'
        if (( ${#out[@]} )) && [[ -z ${out[-1]} ]]; then
          unset 'out[-1]'
        fi
      fi
      continue
    fi
    out+=("$line")
  done
  kept="$(mktemp)"
  for line in ${out[@]+"${out[@]}"}; do
    printf '%s\n' "$line"
  done > "$kept"
  mv "$kept" "$HYPR_MAIN"
  say "took the require line back out of $HYPR_MAIN"
}

uninstall() {
  echo "omarchy-mpv: uninstalling"

  # 1. The CLI symlink, and only when it points into this checkout.
  unlink_ours "$BIN_DEST" "$BIN_SRC"

  # 2. The generated theme fragment (ours: it carries our header).
  if [[ -f "$THEME_CONF" ]] && head -1 "$THEME_CONF" | grep -qF "$THEME_MARKER"; then
    rm -f "$THEME_CONF"
    say "removed $THEME_CONF"
  elif [[ -e "$THEME_CONF" ]]; then
    warn "$THEME_CONF is not ours — left alone."
  fi

  # 3. The two mpv.conf lines the installer appended, and nothing else.
  remove_mpv_conf_lines

  # 4. The theme-set hook.
  if [[ -f "$HOOK_DEST" ]]; then
    rm -f "$HOOK_DEST"
    say "removed the theme-set hook"
  fi

  # 5. The keybinding module and the require block the CLI added.
  if [[ -f "$FRAGMENT" ]]; then
    rm -f "$FRAGMENT"
    say "removed $FRAGMENT"
  fi
  remove_require_block

  echo ""
  echo "Done. Reload Hyprland config:  hyprctl reload"
}

if [[ ${1:-} == --uninstall ]]; then
  uninstall
  exit 0
fi

echo "omarchy-mpv: installing from $PLUGIN_DIR"

# ── 1. Validate the plugin ────────────────────────────────────────────────────
if command -v omarchy >/dev/null 2>&1; then
  omarchy plugin validate "$PLUGIN_DIR" && echo "  manifest OK."
fi

# ── 2. Put the CLI on PATH (symlink, so git pull keeps it current) ────────────
link_cli

# ── 3. Generate the theme fragment now ────────────────────────────────────────
"$BIN_SRC" "${CLI_ARGS[@]}" theme || echo "  WARNING: no applied theme yet — run 'omarchy-mpv theme' later."

# ── 4. Make the user's mpv.conf include our fragment + expose the IPC socket ──
# Nothing the user wrote is ever destroyed: both lines are appended at most once,
# each guarded, and `--uninstall` reverses exactly what this step adds.
mkdir -p "$MPV_DIR"
if [[ ! -f "$MPV_CONF" ]]; then
  printf '# omarchy-mpv integration\n%s\n%s\n' "$THEME_LINE" "$SOCKET_LINE" > "$MPV_CONF"
  echo "  Created $MPV_CONF."
else
  if grep -qF "include=$THEME_CONF" "$MPV_CONF" || grep -q "omarchy-theme.conf" "$MPV_CONF"; then
    echo "  mpv.conf already includes $THEME_CONF."
  else
    printf '\n# omarchy-mpv theme\n%s\n' "$THEME_LINE" >> "$MPV_CONF"
    echo "  Added include= to $MPV_CONF (your config is otherwise untouched)."
  fi
  if grep -qF "input-ipc-server=$SOCKET_PATH" "$MPV_CONF"; then
    echo "  mpv.conf already exposes the plugin's IPC socket."
  else
    # The guard is path-aware: only the plugin's exact socket line counts as
    # done. A pre-existing line at some other path would otherwise shadow ours
    # (anchor grep matches ANY input-ipc-server), leaving `send`/`theme --live`
    # permanently dead while install reported success (#6). Reconcile it by
    # commenting it out (its text is preserved) and add ours last.
    if grep -qE '^[[:space:]]*input-ipc-server=' "$MPV_CONF"; then
      sed -i -E 's|^([[:space:]]*input-ipc-server=.*)|# omarchy-mpv: superseded \1|' "$MPV_CONF"
      echo "  WARNING: $MPV_CONF already set input-ipc-server — commented it out so the plugin's socket is the active one."
    fi
    printf '\n# omarchy-mpv IPC socket\n%s\n' "$SOCKET_LINE" >> "$MPV_CONF"
    echo "  Added input-ipc-server= to $MPV_CONF."
    if ! grep -qF "$SOCKET_LINE" "$MPV_CONF"; then
      echo "  WARNING: could not add $SOCKET_LINE to $MPV_CONF — add it by hand so 'send' and 'theme --live' work."
    fi
  fi
fi

# ── 5. Theme-set hook (uniquely named to avoid basename collisions) ───────────
chmod +x "$PLUGIN_DIR/hooks/mpv-theme-set"
if command -v omarchy >/dev/null 2>&1; then
  omarchy hook install theme-set "$PLUGIN_DIR/hooks/mpv-theme-set"
  echo "  Installed theme-set hook (as mpv-theme-set)."
fi

# ── 6. Wire media-key bindings into Hyprland (rendered from config) ───────────
if [[ -f "$HYPR_MAIN" ]]; then
  # The CLI renders bin/bindings.lua with the configured `keybinding`, so the
  # installed module always matches config/mpv.json.
  "$BIN_SRC" "${CLI_ARGS[@]}" bindings || echo "  WARNING: could not install the keybindings module."
else
  echo "  WARNING: $HYPR_MAIN not found — add: require(\"hypr.mpv-bindings\")"
fi

# Print the chord that was actually installed, read back from the CLI (the same
# value `paths` reports and `bindings` rendered), so the hint cannot drift from
# config/mpv.json (#5).
KEYBINDING="$(printf '%s\n' "$PATHS" | sed -n 's/^keybinding=//p')"
if [[ -z "$KEYBINDING" ]]; then
  KEYBINDING="SUPER + SHIFT + ALT + V"
fi

echo ""
echo "Done. Try:  omarchy-mpv theme   /   omarchy-mpv status   /   omarchy-mpv send toggle"
echo "Media keys: Super + Play/Next/Prev/Stop drive mpv; $KEYBINDING opens it."
echo "Remove it all again with:  ./install.sh --uninstall"
